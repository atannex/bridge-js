// Writes (or, with --check, verifies) a report of the public API: every name
// each package entry point exports, with its declaration as published in
// dist/*.d.ts, comments stripped. A changed report in a pull request is a
// changed public API, to be judged against semver before it ships.
//
//   npm run api:update   rewrite api/ after an intended change
//   npm run api:check    fail when dist/ no longer matches api/ (CI)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
// eslint-disable-next-line @typescript-eslint/no-unsafe-assignment -- JSON.parse is `any`; the JSDoc cast types it.
const pkg = /** @type {{ exports: Record<string, string | { types?: string }> }} */ (
  JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
);

/** @type {{ name: string; file: string }[]} */
const entries = [];
for (const [subpath, target] of Object.entries(pkg.exports)) {
  if (typeof target !== 'object' || target.types === undefined) continue;
  entries.push({
    name: subpath === '.' ? 'index' : subpath.slice(2).replaceAll('/', '-'),
    file: join(root, target.types),
  });
}

const missing = entries.filter((entry) => !existsSync(entry.file));
if (missing.length > 0) {
  console.error(`Build first: ${missing.map((entry) => entry.file).join(', ')} not found.`);
  process.exit(1);
}

const program = ts.createProgram(
  entries.map((entry) => entry.file),
  { module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, noEmit: true },
);
const checker = program.getTypeChecker();
const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

/** @param {string} file */
function report(file) {
  const source = program.getSourceFile(file);
  const moduleSymbol = source === undefined ? undefined : checker.getSymbolAtLocation(source);
  if (moduleSymbol === undefined) throw new Error(`No module symbol for ${file}`);
  const lines = [];
  const exports = checker.getExportsOfModule(moduleSymbol).sort((a, b) => a.name.localeCompare(b.name));
  for (const exported of exports) {
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    for (const declaration of symbol.declarations ?? []) {
      // A variable's declaration is printed with its statement, for `declare const`.
      const node = ts.isVariableDeclaration(declaration) ? declaration.parent.parent : declaration;
      const text = printer.printNode(ts.EmitHint.Unspecified, node, declaration.getSourceFile());
      const renamed = exported.name === symbol.name ? '' : ` // exported as ${exported.name}`;
      lines.push(text + renamed);
    }
  }
  return `// Public API of the "${file.slice(root.length + 1)}" entry point. Generated by scripts/api-report.mjs.\n\n${lines.join('\n\n')}\n`;
}

const outDir = join(root, 'api');
let stale = 0;
mkdirSync(outDir, { recursive: true });
for (const entry of entries) {
  const target = join(outDir, `${entry.name}.api.d.ts`);
  const next = report(entry.file);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
  if (current === next) continue;
  if (check) {
    stale++;
    console.error(`api/${entry.name}.api.d.ts is out of date: the public API changed.`);
  } else {
    writeFileSync(target, next);
    console.log(`Updated api/${entry.name}.api.d.ts`);
  }
}
if (stale > 0) {
  console.error('Review the change against semver, then run `npm run api:update` and commit api/.');
  process.exit(1);
}
